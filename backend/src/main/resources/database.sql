DROP DATABASE IF EXISTS chilla;
CREATE DATABASE chilla CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE chilla;
SET default_storage_engine = InnoDB;

-- Table Projet
CREATE TABLE Projet (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    labpro VARCHAR(255) NOT NULL,
    descrpro VARCHAR(255),
    datedpro DATE NOT NULL,
    datefpro DATE NOT NULL,
    estarchive BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Table Sprint
CREATE TABLE Sprint (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nomsp VARCHAR(255) NOT NULL,
    objectifsp VARCHAR(255),
    datedsp DATE NOT NULL,
    datefsp DATE NOT NULL,
    etatsp ENUM('NON_COMMENCE', 'EN_COURS', 'TERMINE', 'ANNULE') NOT NULL DEFAULT 'NON_COMMENCE',
    IDpro INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (IDpro) REFERENCES Projet(id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Table Membre
CREATE TABLE Membre (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nommem VARCHAR(255) NOT NULL,
    prenommem VARCHAR(255) NOT NULL,
    emailmem VARCHAR(255) NOT NULL UNIQUE,
    motdepassemem VARCHAR(255) NOT NULL,
    datecreamem DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

-- Table Tache
CREATE TABLE Tache (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    labtach VARCHAR(255) NOT NULL,
    descrtach VARCHAR(255),
    datecreatach DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    dateeche DATE NOT NULL,
    estim INT NOT NULL,
    etattach ENUM('NON_COMMENCE', 'EN_COURS', 'TERMINE', 'ANNULE') NOT NULL DEFAULT 'NON_COMMENCE',
    pos INT NOT NULL,
    IDpro INT NOT NULL,
    IDmem INT NOT NULL,
    IDsp INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (IDpro) REFERENCES Projet(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (IDmem) REFERENCES Membre(id) ON DELETE RESTRICT  ON UPDATE CASCADE,
    FOREIGN KEY (IDsp) REFERENCES Sprint(id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Table Invitation
CREATE TABLE Invitation (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    statut ENUM('EN_ATTENTE', 'ACCEPTEE', 'REFUSEE') NOT NULL DEFAULT 'EN_ATTENTE',
    dateevoi DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IDpro INT NOT NULL,
    IDemetteur INT NOT NULL,
    IDrecepteur INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (IDpro) REFERENCES Projet(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (IDemetteur) REFERENCES Membre(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (IDrecepteur) REFERENCES Membre(id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Table Membre_Projet
CREATE TABLE Membre_Projet (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    IDmem INT NOT NULL,
    IDpro INT NOT NULL,
    rolemem ENUM('CHEF_DE_PROJET', 'MEMBRE') NOT NULL DEFAULT 'MEMBRE',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_membre_projet (IDmem, IDpro),
    FOREIGN KEY (IDmem) REFERENCES Membre(id) ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (IDpro) REFERENCES Projet(id) ON DELETE CASCADE ON UPDATE CASCADE
);

-- Table Notification
CREATE TABLE Notification (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    message VARCHAR(255) NOT NULL,
    datecreanotif DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estlue BOOLEAN NOT NULL DEFAULT FALSE,
    IDmem INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (IDmem) REFERENCES Membre(id) ON DELETE CASCADE ON UPDATE CASCADE
);